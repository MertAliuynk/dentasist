// ISO2 + dial code + display name for the country picker in PhoneInput.
// Flags are rendered from the ISO2 code via regional indicator symbols
// (see flagEmoji below) rather than hardcoded emoji, so this list only needs
// to carry the code/name/dial-code data itself.
export type PhoneCountry = { iso2: string; name: string; dialCode: string };

export function flagEmoji(iso2: string): string {
  return iso2
    .toUpperCase()
    .replace(/./g, (c) => String.fromCodePoint(127397 + c.charCodeAt(0)));
}

